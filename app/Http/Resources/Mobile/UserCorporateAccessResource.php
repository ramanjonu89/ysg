<?php

namespace App\Http\Resources\Mobile;

use App\Utility\DateTimeHelper;
use Illuminate\Http\Resources\Json\JsonResource;

/**
 * @OA\Schema(
 *     schema="UserCorporateAccess",
 *     type="object",
 *     title="User Corporate Access Resource",
 *     description="Represents the user's corporate access information, including expiry and domain details.",
 *     @OA\Property(
 *         property="id",
 *         type="integer",
 *         example=123,
 *         description="The unique identifier of the corporate access record."
 *     ),
 *     @OA\Property(
 *         property="expired",
 *         type="boolean",
 *         example=false,
 *         description="Indicates whether the corporate access has expired."
 *     ),
 *     @OA\Property(
 *         property="expire_at",
 *         type="string",
 *         format="date-time",
 *         nullable=true,
 *         example="2025-12-31 23:59:59",
 *         description="The expiration date and time of the corporate access, if applicable."
 *     ),
 *     @OA\Property(
 *         property="domain",
 *         type="string",
 *         example="@ninjavan.co",
 *         description="The domain associated with the corporate access."
 *     ),
 *     @OA\Property(
 *         property="duration",
 *         type="string",
 *         example="30 days",
 *         description="A human-readable string representing the duration of the corporate access, generated by DateTimeHelper."
 *     ),
 *     @OA\Property(
 *         property="is_active",
 *         type="boolean",
 *         example=true,
 *         description="Indicates whether the corporate access is currently active."
 *     )
 * )
 */

class UserCorporateAccessResource extends JsonResource
{
    public function toArray($request)
    {
        return [
            'id' => $this->id,
            'expired' => $this->expire_at ? $this->expire_at->isPast() : false,
            'expire_at' => $this->expire_at ? $this->expire_at->format('Y-m-d H:i:s') : null,
            'domain'    => $this->domain,
            'duration'  => DateTimeHelper::getDurationString($this->duration),
            'is_active' => $this->is_active,
        ];
    }
}